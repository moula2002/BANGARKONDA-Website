export function getProjectBySlug(slug) {
  if (!slug) return null;
  return projectsData.find(
    p => p.slug.toLowerCase() === slug.toLowerCase() || p.id.toLowerCase() === slug.toLowerCase()
  );
}

export function getRelatedProjects(currentId, limit = 3) {
  const current = projectsData.find(p => p.id === currentId || p.slug === currentId);
  if (!current) return projectsData.slice(0, limit);

  // First pick same category, then other categories
  const sameCategory = projectsData.filter(p => p.id !== current.id && p.category === current.category);
  const otherCategory = projectsData.filter(p => p.id !== current.id && p.category !== current.category);

  return [...sameCategory, ...otherCategory].slice(0, limit);
}
